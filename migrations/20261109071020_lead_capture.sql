-- Lead capture (iClosed-style): record what guests type into a booking form
-- before they submit, so a host can follow up on abandoned bookings.
--
-- Off by default at every level. An admin global switch and a per-event-type
-- toggle must both be on for anything to be recorded, and the host must have
-- acknowledged once, per event type, that bookers are informed (GDPR).
--
-- The guest phone number is not stored here as a booking concern: calrs
-- already collects it for SMS (`event_types.sms_phone_mode`,
-- `bookings.guest_phone`, migration 062). Lead capture only asks for a phone
-- on the gate when that mode is not 'off'.

CREATE TABLE IF NOT EXISTS partial_bookings (
    id              TEXT PRIMARY KEY,
    event_type_id   TEXT NOT NULL REFERENCES event_types(id) ON DELETE CASCADE,
    -- Resolved at insert time so the leads page can scope per host without
    -- joining through event_types. NULL for event types with no creator.
    host_user_id    TEXT REFERENCES users(id) ON DELETE SET NULL,
    -- Stable id generated by the browser (sessionStorage), opaque to the
    -- server. UNIQUE so the keystroke upsert is a plain ON CONFLICT.
    lead_id         TEXT NOT NULL UNIQUE,
    -- Captured fields. All optional: capture is incremental, so a row may
    -- hold half an email address.
    name            TEXT,
    email           TEXT,
    phone           TEXT,
    notes           TEXT,
    -- Audit metadata.
    ip              TEXT,
    user_agent      TEXT,
    -- The slot the guest was heading for.
    target_date     TEXT,
    target_time     TEXT,
    target_tz       TEXT,
    -- Attribution, captured client-side from utm_* and document.referrer.
    utm_source      TEXT,
    utm_medium      TEXT,
    utm_campaign    TEXT,
    referrer        TEXT,
    -- Set when the guest finishes the booking. NULL = still partial.
    completed_at    TEXT,
    -- Worklist state set by the host. Archived rows leave the default view.
    contacted_at    TEXT,
    archived_at     TEXT,
    -- Set once the abandonment alert went out, so each lead alerts once.
    notified_at     TEXT,
    created_at      TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_partial_bookings_event_type ON partial_bookings(event_type_id);
CREATE INDEX IF NOT EXISTS idx_partial_bookings_host ON partial_bookings(host_user_id);
CREATE INDEX IF NOT EXISTS idx_partial_bookings_completed ON partial_bookings(completed_at);
CREATE INDEX IF NOT EXISTS idx_partial_bookings_updated ON partial_bookings(updated_at);
CREATE INDEX IF NOT EXISTS idx_partial_bookings_archived ON partial_bookings(archived_at);

-- Per-event-type opt-in, plus the one-time acknowledgement that bookers are
-- informed. Both stay on the event type, not on a user.
ALTER TABLE event_types ADD COLUMN lead_capture INTEGER NOT NULL DEFAULT 0;
ALTER TABLE event_types ADD COLUMN lead_capture_acknowledged_at TEXT;

-- Global switch, retention window (captured rows are purged after this many
-- days) and an optional link to the operator's privacy page, which replaces
-- the inline notice on the booking pages.
ALTER TABLE auth_config ADD COLUMN lead_capture_enabled INTEGER NOT NULL DEFAULT 0;
ALTER TABLE auth_config ADD COLUMN lead_retention_days INTEGER NOT NULL DEFAULT 30;
ALTER TABLE auth_config ADD COLUMN legal_mentions_url TEXT;

-- Keep the statistics, drop the person: when a lead turns into a booking, blank
-- the name, email, phone, notes, IP and browser string, since the booking holds
-- what is needed.
ALTER TABLE auth_config ADD COLUMN lead_anonymize_on_booking INTEGER NOT NULL DEFAULT 0;
-- Minutes a guest must stay silent before the host is told about the lead.
ALTER TABLE auth_config ADD COLUMN lead_alert_after_minutes INTEGER NOT NULL DEFAULT 30;
-- 0: one email per lead. N > 0: one email per host and per N minutes, listing
-- the leads that piled up.
ALTER TABLE auth_config ADD COLUMN lead_digest_minutes INTEGER NOT NULL DEFAULT 0;

-- A combined page (/u/alice+bob/...) concerns every user named in its URL: each
-- of them sees the lead and is alerted about it.
CREATE TABLE IF NOT EXISTS partial_booking_participants (
    lead_id TEXT NOT NULL REFERENCES partial_bookings(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (lead_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_partial_booking_participants_user
    ON partial_booking_participants(user_id);
